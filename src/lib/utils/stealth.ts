const TIMEZONES = [
  'America/New_York',
  'America/Chicago',
  'America/Denver',
  'America/Los_Angeles',
  'Europe/London',
  'Europe/Madrid',
  'Europe/Berlin',
  'Asia/Tokyo',
]

const LOCALES = ['en-US', 'en-GB', 'es-ES', 'de-DE', 'fr-FR']

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

export function getStealthConfig(proxyUrl?: string): BrowserContextOptions {
  return {
    userAgent: pick(USER_AGENTS),
    viewport: {
      width: 1280 + Math.floor(Math.random() * 160),
      height: 720 + Math.floor(Math.random() * 180),
    },
    locale: pick(LOCALES),
    timezoneId: pick(TIMEZONES),
    deviceScaleFactor: 1,
    hasTouch: false,
    isMobile: false,
    ...(proxyUrl ? { proxy: { server: proxyUrl } } : {}),
  }
}
